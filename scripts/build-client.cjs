#!/usr/bin/env node
/**
 * Assemble the browser bundle for `@aghost-prj/dsh-auto-review-model`.
 *
 * The Host and Client Typert faces are generated from one dependency-free
 * module, `src/typert.contract.ts`. TypeScript compiles that module normally for
 * the Node artifacts (`lib/typert.host.js`, `lib/typert.remote-client.js`), but
 * the browser half is a single classic script that cannot import an ESM module,
 * so this script embeds a CommonJS transpilation of the same source in front of
 * the tsc-emitted client body.
 *
 * The embedded prelude registers the package's `./remote` contribution as a
 * package-local module under the loader id `<package>/client.remote.js`, which
 * is the id the loader's `chunk` mechanism owns and invalidates on HMR reload
 * (`invalidate()` removes `<package>/client.*` factories). The client body then
 * requires that exact specifier and mounts the contribution through
 * `ctx.remote.$mount()`, so the browser half consumes this package's `./remote`
 * artifact instead of duplicating the wire contract by hand.
 *
 * The script is idempotent: the tsc output is the body after the
 * marker line, so running it twice does not double-prepend the prelude. Only the
 * committed `typescript` devDependency is used; no runtime dependency (zod or a
 * Harness package) enters the bundle.
 *
 * @module scripts/build-client
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

/** Repository root (this file lives in `<root>/scripts`). */
const ROOT = path.resolve(__dirname, '..');
/** Single source of truth for both Typert faces. */
const CONTRACT_SOURCE = path.join(ROOT, 'src', 'typert.contract.ts');
/** tsc output of `src/client/client.ts`, rewritten in place into the final bundle. */
const CLIENT_BUNDLE = path.join(ROOT, 'client', 'client.js');
/** First line of a generated bundle, used to detect and replace a prior prelude. */
const PRELUDE_MARKER = '/* @aghost-prj/dsh-auto-review-model:generated-client-remote-prelude */';
/** Line separating the generated prelude from the tsc-emitted client body. */
const BODY_MARKER = '/* @aghost-prj/dsh-auto-review-model:client-bundle-body */';

/** Fail with one actionable message instead of a stack trace. */
function fail(message) {
  console.error(`build-client: ${message}`);
  process.exit(1);
}

/** Transpile the contract module to CommonJS text embedded in the prelude. */
function transpileContract() {
  const source = fs.readFileSync(CONTRACT_SOURCE, 'utf8');
  const result = ts.transpileModule(source, {
    fileName: 'typert.contract.ts',
    reportDiagnostics: true,
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      removeComments: false,
      newLine: ts.NewLineKind.LineFeed,
    },
  });
  const errors = (result.diagnostics || []).filter(
    (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
  );
  if (errors.length > 0) {
    const text = errors
      .map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
      .join('; ');
    fail(`cannot transpile ${path.relative(ROOT, CONTRACT_SOURCE)}: ${text}`);
  }
  if (typeof result.outputText !== 'string' || result.outputText.trim() === '') {
    fail(`transpiling ${path.relative(ROOT, CONTRACT_SOURCE)} produced no output`);
  }
  return result.outputText;
}

/**
 * Build the generated prelude registering the package-local Remote contribution.
 * @param {string} contractSource - CommonJS contract output.
 * @returns {string} classic-script source.
 */
function buildPrelude(contractSource) {
  return [
    PRELUDE_MARKER,
    '/* Generated by scripts/build-client.cjs from src/typert.contract.ts. Do not edit. */',
    '(function () {',
    '  var module = { exports: {} };',
    '  (function (exports, module) {',
    contractSource.trimEnd(),
    '  })(module.exports, module);',
    '  var contract = module.exports;',
    '  window.__ModuleLoader__.load({',
    '    id: contract.PACKAGE_NAME,',
    '    chunk: contract.REMOTE_CHUNK_FILE,',
    '    factory: function () {',
    '      var contribution = contract.createRemoteContribution();',
    '      return { TYPERT_REMOTE: contribution, default: contribution };',
    '    },',
    '  });',
    '})();',
    '',
    BODY_MARKER,
    '',
  ].join('\n');
}

/** Strip a previously generated prelude so the script is idempotent. */
function readClientBody() {
  if (!fs.existsSync(CLIENT_BUNDLE)) {
    fail(`${path.relative(ROOT, CLIENT_BUNDLE)} is missing; run tsc -p tsconfig.client.json first`);
  }
  const current = fs.readFileSync(CLIENT_BUNDLE, 'utf8');
  const markerIndex = current.indexOf(BODY_MARKER);
  if (markerIndex >= 0) return current.slice(markerIndex + BODY_MARKER.length).replace(/^\r?\n/, '');
  return current;
}

function main() {
  const contractSource = transpileContract();
  const body = readClientBody();
  if (!body.includes('window.__ModuleLoader__.load')) {
    fail('client body does not register a window.__ModuleLoader__.load factory');
  }
  // TypeScript's classic-script emitter can leave trailing spaces after
  // elided comments/formatting. Keep the committed artifact diff-clean while
  // preserving every non-whitespace byte and the source-derived body.
  const output = (buildPrelude(contractSource) + body).replace(/[ \t]+$/gm, '');
  fs.writeFileSync(CLIENT_BUNDLE, output, 'utf8');
  console.log(
    `build-client: embedded Typert contribution in ${path.relative(ROOT, CLIENT_BUNDLE)} from ${path.relative(ROOT, CONTRACT_SOURCE)}`,
  );
}

main();
